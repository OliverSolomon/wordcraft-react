// Regenerate packages/wordcraft-react/src/google-fonts.ts from the Fontsource catalogue of Google
// Fonts (all SIL Open Font License or Apache). Usage: node scripts/update-font-catalog.mjs
import { writeFileSync } from 'node:fs';

const res = await fetch('https://api.fontsource.org/v1/fonts');
if (!res.ok) throw new Error(`fontsource: ${res.status}`);
const all = await res.json();
const cats = { 'sans-serif': 's', serif: 'r', display: 'd', handwriting: 'h', monospace: 'm' };
const rows = [];
for (const f of all) {
  if (f.type !== 'google' || f.category === 'icons') continue;
  const flags = (f.weights?.includes(700) ? 'b' : '') + (f.styles?.includes('italic') ? 'i' : '');
  const id = f.id === f.family.toLowerCase().replace(/ /g, '-') ? 0 : f.id;
  const sub = f.defSubset && f.defSubset !== 'latin' ? f.defSubset : 0;
  const row = [f.family, id, cats[f.category] ?? 's', flags, sub];
  while (row.length && (row[row.length - 1] === 0 || row[row.length - 1] === '')) row.pop();
  rows.push(row);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const out = `// Generated by scripts/update-font-catalog.mjs from the Fontsource catalogue (Google Fonts).
// Each row: [family, id (0 = family in kebab case), category (s sans, r serif, d display,
// h handwriting, m mono), flags (b = has bold, i = has italic), default subset (0 = latin)].
export type FontRow = [string, (string | 0)?, string?, string?, (string | 0)?];
export const GOOGLE_FONTS: FontRow[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../packages/wordcraft-react/src/google-fonts.ts', import.meta.url), out);
console.log(`${rows.length} families`);
